import { writeFile } from 'node:fs/promises';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { properties } from '../src/data.js';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(projectRoot, 'supabase/seed.sql');
const columns = [
  'id', 'type', 'house_type', 'title', 'price', 'location', 'beds', 'baths',
  'sqft', 'image', 'gallery', 'tag', 'description', 'agent',
];

const toSqlString = (value) => `'${String(value ?? '').replaceAll("'", "''")}'`;

const toSqlNumber = (value, field, id) => {
  if (typeof value !== 'number' || !Number.isFinite(value)) {
    throw new Error(`Property ${id} has an invalid numeric value for ${field}.`);
  }

  return String(value);
};

const ids = properties.map(({ id }) => id);
if (new Set(ids).size !== ids.length) {
  throw new Error('Property IDs in src/data.js must be unique.');
}

const rows = properties.map((property) => {
  const gallery = Array.isArray(property.gallery) ? property.gallery : [];
  const gallerySql = gallery.length
    ? `array[${gallery.map(toSqlString).join(', ')}]::text[]`
    : "'{}'::text[]";

  const values = [
    toSqlNumber(property.id, 'id', property.id),
    toSqlNumber(property.type, 'type', property.id),
    toSqlString(property.houseType || 'Rumah'),
    toSqlString(property.title),
    toSqlNumber(property.price, 'price', property.id),
    toSqlString(property.location),
    toSqlNumber(property.beds ?? 0, 'beds', property.id),
    toSqlNumber(property.baths ?? 0, 'baths', property.id),
    toSqlNumber(property.sqft ?? 0, 'sqft', property.id),
    toSqlString(property.image),
    gallerySql,
    toSqlString(property.tag),
    toSqlString(property.description),
    toSqlString(property.agent),
  ];

  return `  (${values.join(', ')})`;
});

const updates = columns
  .slice(1)
  .map((column) => `  ${column} = excluded.${column}`)
  .join(',\n');

const sql = [
  '-- Generated from src/data.js. Do not edit this file directly.',
  'insert into public.properties',
  `  (${columns.join(', ')})`,
  'values',
  rows.join(',\n'),
  'on conflict (id) do update set',
  `${updates};`,
  '',
].join('\n');

await writeFile(outputPath, sql, 'utf8');
console.log(`Generated ${relative(projectRoot, outputPath)} with ${properties.length} properties.`);
